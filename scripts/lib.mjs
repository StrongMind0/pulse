// Shared helpers for the developer scripts. Node standard library only, so
// they run before any `npm install`.
import { randomBytes } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

export const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
export const IS_WIN = process.platform === "win32";
export const ENV_FILE = join(ROOT, ".env");

const secret = (bytes) => randomBytes(bytes).toString("base64url");

/** Loads .env, creating it with fresh random secrets on first run. */
export function loadEnv() {
  if (!existsSync(ENV_FILE)) {
    const lines = [
      "# Generated by scripts/dev.mjs on first run. Never commit this file.",
      `PULSE_DEVICE_TOKEN=${secret(24)}`,
      `PULSE_SERVICE_TOKEN=${secret(24)}`,
      `PULSE_JWT_SECRET=${secret(48)}`,
      "PULSE_ADMIN_USER=admin",
      `PULSE_ADMIN_PASSWORD=${secret(9)}`,
      "",
    ];
    writeFileSync(ENV_FILE, lines.join("\n"), { mode: 0o600 });
    console.log(color("33", "created .env with random secrets"));
  }
  const env = {};
  for (const line of readFileSync(ENV_FILE, "utf8").split(/\r?\n/)) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/);
    if (m) env[m[1]] = m[2];
  }
  return env;
}

export function color(code, text) {
  return process.stdout.isTTY ? `\x1b[${code}m${text}\x1b[0m` : text;
}

export function simBinary() {
  return join(ROOT, "firmware", "build", IS_WIN ? "pulse-sim.exe" : "pulse-sim");
}

export async function waitForHttp(url, timeoutMs, isAlive = () => true) {
  const deadline = Date.now() + timeoutMs;
  while (Date.now() < deadline) {
    if (!isAlive()) return false;
    try {
      const res = await fetch(url, { signal: AbortSignal.timeout(1000) });
      if (res.ok) return true;
    } catch {
      /* not up yet */
    }
    await new Promise((r) => setTimeout(r, 500));
  }
  return false;
}
